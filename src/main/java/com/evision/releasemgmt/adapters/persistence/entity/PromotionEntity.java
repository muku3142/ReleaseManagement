package com.evision.releasemgmt.adapters.persistence.entity;

import com.evision.releasemgmt.domain.promotion.PromotionOutcome;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.Immutable;
import org.springframework.data.domain.Persistable;

import java.time.Instant;
import java.util.UUID;

// D-07-11: Hibernate never issues an UPDATE for an @Immutable entity; the DB trigger is the real guarantee.
// Always new: ids are generated by the domain, so Spring Data must persist() rather than merge().
@Entity
@Immutable
@Table(name = "promotion")
public class PromotionEntity implements Persistable<UUID> {

    @Id
    private UUID id;

    @Column(name = "release_id", nullable = false)
    private UUID releaseId;

    @Column(name = "stage_id", nullable = false)
    private UUID stageId;

    @Column(name = "outcome", nullable = false)
    @Enumerated(EnumType.STRING)
    private PromotionOutcome outcome;

    @Column(name = "deployed_at", nullable = false)
    private Instant deployedAt;

    @Column(name = "recorded_at", nullable = false)
    private Instant recordedAt;

    @Column(name = "recorded_by", nullable = false)
    private String recordedBy;

    @Column(name = "note")
    private String note;

    @Column(name = "supersedes_id")
    private UUID supersedesId;

    @Column(name = "correction_reason")
    private String correctionReason;

    protected PromotionEntity() {
    }

    public PromotionEntity(UUID id, UUID releaseId, UUID stageId, PromotionOutcome outcome, Instant deployedAt,
                           Instant recordedAt, String recordedBy, String note, UUID supersedesId,
                           String correctionReason) {
        this.id = id;
        this.releaseId = releaseId;
        this.stageId = stageId;
        this.outcome = outcome;
        this.deployedAt = deployedAt;
        this.recordedAt = recordedAt;
        this.recordedBy = recordedBy;
        this.note = note;
        this.supersedesId = supersedesId;
        this.correctionReason = correctionReason;
    }

    @Override
    public UUID getId() {
        return id;
    }

    @Override
    public boolean isNew() {
        return true;
    }

    public UUID getReleaseId() {
        return releaseId;
    }

    public UUID getStageId() {
        return stageId;
    }

    public PromotionOutcome getOutcome() {
        return outcome;
    }

    public Instant getDeployedAt() {
        return deployedAt;
    }

    public Instant getRecordedAt() {
        return recordedAt;
    }

    public String getRecordedBy() {
        return recordedBy;
    }

    public String getNote() {
        return note;
    }

    public UUID getSupersedesId() {
        return supersedesId;
    }

    public String getCorrectionReason() {
        return correctionReason;
    }
}
