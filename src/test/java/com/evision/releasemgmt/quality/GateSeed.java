    private UUID create(String name, String version, Instant createdAt, List<TicketDetail> tickets, Instant addedAt) {
        Release created = releases.create(Release.create(name, version, projectKey(tickets.getFirst().key()), ACTOR,
                createdAt), tickets.stream().map(ticket -> item(ticket, addedAt)).toList());
        releaseIds.put(name + " " + version, created.id());
        return created.id();
    }

    private static String projectKey(String ticketKey) {
        return ticketKey.substring(0, ticketKey.indexOf('-'));
    }

    private static ReleaseItem item(TicketDetail ticket, Instant addedAt) {
        return new ReleaseItem(ticket, addedAt, CodeLinks.notAttempted());
    }

    private static TicketDetail ticket(String key, String summary, String type, String status, String resolution,
                                         String assignee, String component, String description, List<String> comments,
                                         List<String> fixVersions, int storyPoints) {
        StatusCategory category = "Done".equals(status) ? StatusCategory.DONE : StatusCategory.IN_PROGRESS;
        return new TicketDetail(key, summary, type, status, resolution, assignee, "Rae Collins", fixVersions, component,
                description, comments, comments.size(), null, ago(16), category, BigDecimal.valueOf(storyPoints), true);
    }

