    private static CodeLinks linked(String sha, String message, String author, String prId, String prTitle,
                                    String branch) {
        return new CodeLinks(EnrichmentStatus.LINKED, null, false, ago(20), CommitsSource.KEY_TAGGED,
                List.of(new LinkedPullRequest("repo-1", prId, prTitle, "completed",
                        "https://dev.azure.com/example/project/_git/repo/pullrequest/" + prId, branch, "main", true,
                        ago(20))),
                List.of(new LinkedCommit(sha, message, author, ago(25),
                        "https://dev.azure.com/example/project/_git/repo/commit/" + sha)),
                List.of(branch), StatusHistory.notRead());
    }

    private static CodeLinks linkedWithHistory(String sha, String message, String author, String prId, String prTitle,
                                               String branch) {
        CodeLinks base = linked(sha, message, author, prId, prTitle, branch);
        StatusHistory history = StatusHistory.derive(List.of(
                change(35, "1", "3", StatusCategory.TO_DO, StatusCategory.IN_PROGRESS),
                change(34, "3", "10001", StatusCategory.IN_PROGRESS, StatusCategory.DONE),
                change(33, "10001", "3", StatusCategory.DONE, StatusCategory.IN_PROGRESS),
                change(32, "3", "10001", StatusCategory.IN_PROGRESS, StatusCategory.DONE),
                change(31, "10001", "3", StatusCategory.DONE, StatusCategory.IN_PROGRESS),
                change(30, "3", "10001", StatusCategory.IN_PROGRESS, StatusCategory.DONE)), ago(16));
        return new CodeLinks(base.status(), null, false, base.attemptedAt(), base.commitsSource(), base.pullRequests(),
                base.commits(), base.branches(), history);
    }

    private static StatusChange change(int daysAgo, String from, String to, StatusCategory fromCategory,
                                       StatusCategory toCategory) {
        return new StatusChange(ago(daysAgo), from, to, fromCategory, toCategory);
    }

    private void manual(UUID releaseId, String title, ManualItemCategory category, String description, Instant at) {
        releases.addManualItem(releaseId, ManualItem.create(title, description, category, at));
    }

    private void snapshot(UUID releaseId, TemplateDocumentType type, int revision, String markdown, Instant at) {
        Template template = activeTemplates.get(type);
        snapshots.create(DocumentSnapshot.create(releaseId, type, revision, markdown, template.id(), template.name(),
                template.body(), ChromeFields.empty(), ACTOR, at), null);
    }

    private void freeze(UUID releaseId, Instant at) {
        releases.freeze(releaseId, ACTOR, at);
    }

    private void promote(UUID releaseId, String stageName, Instant at, PromotionOutcome outcome, String note) {
        promotions.appendUnderLock(releaseId, history -> {
            Stage stage = history.stages().stream().filter(s -> s.name().equals(stageName)).findFirst().orElseThrow();
            return history.record(new PromotionDraft(stage.id(), outcome, at, note), ACTOR, at);
        });
    }

